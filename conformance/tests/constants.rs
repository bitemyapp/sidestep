//! The string constants programs name, with the values macOS gives them:
//! each is a data symbol holding a constant string, which a Linux program
//! must find exported to link. (The ones classes here use are checked with
//! their classes; these are the rest.) Runs on macOS against Apple's.
#![allow(deprecated)]

use sidestep as _;

macro_rules! strings {
    ($($path:path = $value:literal,)*) => {
        #[test]
        fn string_constants() {
            let mut wrong = Vec::new();
            $(
                // SAFETY: a constant string AppKit or Foundation exports.
                let value = unsafe { $path }.to_string();
                if value != $value {
                    wrong.push(format!("{} is {value:?}, not {:?}", stringify!($path), $value));
                }
            )*
            assert!(wrong.is_empty(), "{wrong:#?}");
        }
    };
}

macro_rules! optional_strings {
    ($($path:path = $value:literal,)*) => {
        #[test]
        fn optional_string_constants() {
            $(
                // SAFETY: as above, declared as possibly nil.
                let value = unsafe { $path }.map(|v| v.to_string());
                assert_eq!(value.as_deref(), Some($value), "{}", stringify!($path));
            )*
        }
    };
}

