fn class(name: &str) -> &'static AnyClass {
    AnyClass::get(&CString::new(name).unwrap()).unwrap_or_else(|| panic!("no class {name}"))
}

fn object<T: objc2::Message>(value: Retained<T>) -> Retained<AnyObject> {
    // SAFETY: every object is an AnyObject.
    unsafe { Retained::cast_unchecked(value) }
}

fn frame() -> NSRect {
    NSRect::new(NSPoint::ZERO, NSSize::new(100.0, 100.0))
}

