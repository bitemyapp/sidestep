fn main() {
    let mtm = MainThreadMarker::new().expect("the test's main runs on the main thread");
    let app = NSApplication::sharedApplication(mtm);
    app.setActivationPolicy(NSApplicationActivationPolicy::Accessory);
    if !cfg!(debug_assertions) {
        println!("test every_sent_selector_responds ... ignored (debug builds)");
        return;
    }
    let mut missing = Vec::new();
    let mut made: std::collections::HashMap<&str, Vec<Retained<AnyObject>>> = Default::default();
    for &(class_method, name, selector) in SENT {
        let sel = Sel::register(&CString::new(selector).unwrap());
        let cls = class(name);
        if class_method {
            let responds: bool = unsafe { msg_send![cls, respondsToSelector: sel] };
            if !responds {
                missing.push(format!("+[{name} {selector}]"));
            }
            continue;
        }
        // Initializers belong to allocated objects, not made ones.
        let objects = made.entry(name).or_insert_with(|| instances(mtm, name));
        if objects.is_empty() || selector.starts_with("init") {
            let mut responds: bool = unsafe { msg_send![cls, instancesRespondToSelector: sel] };
            if !responds && selector.starts_with("init") {
                // A class cluster: its placeholder initializes. Kept, not
                // given back uninitialized.
                let allocated: Allocated<AnyObject> = unsafe { msg_send![cls, alloc] };
                responds = unsafe { msg_send![Allocated::as_ptr(&allocated), respondsToSelector: sel] };
                std::mem::forget(allocated);
            }
            if !responds {
                missing.push(format!("-[{name} {selector}]"));
            }
            continue;
        }
        for object in objects.iter() {
            let responds: bool = unsafe { msg_send![&**object, respondsToSelector: sel] };
            if !responds {
                missing.push(format!("-[{name} {selector}] on a {}", object.class().name().to_str().unwrap()));
            }
        }
    }
    assert!(missing.is_empty(), "{} selectors not found:\n{}", missing.len(), missing.join("\n"));
    println!("test every_sent_selector_responds ... ok");
}
