//! Every extern static and function objc2-core-graphics declares under
//! the features Sidestep's crates enable, referenced so a Linux build
//! links each: one Sidestep stops exporting fails this test's link. The
//! known gaps (docs/abi.md) are left out. Written by `scripts/link-
//! closure`; run it again when the features or the exports change.
#![cfg(not(target_vendor = "apple"))]
#![allow(deprecated, unused_unsafe, clippy::fn_to_numeric_cast_any)]

use sidestep as _;

macro_rules! addresses {
    (statics: [$($s:path,)*] functions: [$($f:path,)*]) => {
        #[test]
        fn every_symbol_links() {
            let statics: &[(&str, usize)] = &[$((stringify!($s), unsafe { &raw const $s } as usize),)*];
            let functions: &[(&str, usize)] = &[$((stringify!($f), $f as *const () as usize),)*];
            // Through black_box, so no build folds the checks and drops the references.
            let (statics, functions) = std::hint::black_box((statics, functions));
            for (name, address) in statics.iter().chain(functions) {
                assert_ne!(*address, 0, "{name}");
            }
            assert_eq!(statics.len() + functions.len(), 388);
        }
    };
}

