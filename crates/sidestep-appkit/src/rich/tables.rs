/// The color CSS names `name` (any case).
pub(crate) fn css_color(name: &str) -> Option<u32> {
    let name = name.to_ascii_lowercase();
    CSS_COLORS.binary_search_by(|(n, _)| (*n).cmp(name.as_str())).ok().map(|i| CSS_COLORS[i].1)
}

/// The character the named reference `name` (without `&` and `;`) stands
/// for. Names are case-sensitive.
pub(crate) fn entity(name: &str) -> Option<char> {
    ENTITIES.binary_search_by(|(n, _)| (*n).cmp(name)).ok().map(|i| ENTITIES[i].1)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn code_pages_decode_and_encode() {
        assert_eq!(CodePage::Cp1252.decode(0x80), '€');
        assert_eq!(CodePage::Cp1252.decode(0xE9), 'é');
        assert_eq!(CodePage::Cp1252.decode(0x81), '\u{81}', "undefined bytes read as Latin 1");
        assert_eq!(CodePage::Cp1251.decode(0xC0), 'А');
        assert_eq!(CodePage::MacRoman.decode(0x8E), 'é');
        assert_eq!(CodePage::Cp1250.decode(0x8A), 'Š');
        assert_eq!(CodePage::Cp1252.encode('€'), Some(0x80));
        assert_eq!(CodePage::Cp1252.encode('é'), Some(0xE9));
        assert_eq!(CodePage::Cp1252.encode('日'), None);
        assert_eq!(CodePage::Cp1252.encode('\u{81}'), None);
        assert_eq!(CodePage::from_label("ISO-8859-1"), Some(CodePage::Cp1252));
    }

    #[test]
    fn names_are_found() {
        assert!(CSS_COLORS.windows(2).all(|w| w[0].0 < w[1].0));
        assert!(ENTITIES.windows(2).all(|w| w[0].0 < w[1].0));
        assert_eq!(css_color("CornflowerBlue"), Some(0x6495ed));
        assert_eq!(css_color("nosuch"), None);
        assert_eq!((entity("eacute"), entity("Eacute"), entity("hellip")), (Some('é'), Some('É'), Some('…')));
        assert_eq!(entity("nosuch"), None);
    }
}
