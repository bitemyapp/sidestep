//! Tables the readers and writers look things up in: single-byte code
//! pages (RTF's `\ansicpg`, `\fcharset` and `\mac`, HTML's `charset`),
//! CSS's named colors and HTML's named character references (HTML 4's set,
//! and `&apos;`).
//!
//! Each code page gives the characters of bytes 0x80 to 0xFF; 0 marks a
//! byte the page leaves undefined, read as the C1 control of that value, as
//! Latin 1 reads it.

/// A single-byte code page.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum CodePage {
    Cp1250,
    Cp1251,
    Cp1252,
    Cp1253,
    Cp1254,
    Cp1257,
    MacRoman,
    Cp437,
    Cp850,
    /// ISO 8859-1: bytes are their code points.
    Latin1,
}

impl CodePage {
    /// The page a Windows code page number (RTF's `\ansicpgN`) names.
    pub fn from_number(n: i32) -> Option<CodePage> {
        Some(match n {
            1250 => CodePage::Cp1250,
            1251 => CodePage::Cp1251,
            1252 => CodePage::Cp1252,
            1253 => CodePage::Cp1253,
            1254 => CodePage::Cp1254,
            1257 => CodePage::Cp1257,
            10000 => CodePage::MacRoman,
            437 => CodePage::Cp437,
            850 => CodePage::Cp850,
            28591 => CodePage::Latin1,
            _ => return None,
        })
    }

    /// The page an RTF font's `\fcharsetN` implies, for the charsets with
    /// a single-byte page here.
    pub fn from_charset(n: i32) -> Option<CodePage> {
        Some(match n {
            0 => CodePage::Cp1252,
            77 => CodePage::MacRoman,
            161 => CodePage::Cp1253,
            162 => CodePage::Cp1254,
            186 => CodePage::Cp1257,
            204 => CodePage::Cp1251,
            238 => CodePage::Cp1250,
            _ => return None,
        })
    }

    /// The page an HTML `charset` label names, as browsers take them
    /// (ISO 8859-1 and ASCII mean Windows-1252).
    pub fn from_label(label: &str) -> Option<CodePage> {
        let l = label.trim().to_ascii_lowercase();
        Some(match l.as_str() {
            "windows-1252" | "cp1252" | "x-cp1252" | "iso-8859-1" | "iso8859-1" | "latin1" | "l1" | "us-ascii"
            | "ascii" | "iso_8859-1" | "cp819" | "ibm819" => CodePage::Cp1252,
            "windows-1250" | "cp1250" | "x-cp1250" => CodePage::Cp1250,
            "windows-1251" | "cp1251" | "x-cp1251" => CodePage::Cp1251,
            "windows-1253" | "cp1253" | "x-cp1253" => CodePage::Cp1253,
            "windows-1254" | "cp1254" | "x-cp1254" | "iso-8859-9" | "latin5" => CodePage::Cp1254,
            "windows-1257" | "cp1257" | "x-cp1257" => CodePage::Cp1257,
            "macintosh" | "mac" | "x-mac-roman" | "csmacintosh" => CodePage::MacRoman,
            _ => return None,
        })
    }

    /// The character byte `b` stands for.
    pub fn decode(self, b: u8) -> char {
        if b < 0x80 {
            return char::from(b);
        }
        let table = match self {
            CodePage::Latin1 => return char::from(b),
            CodePage::Cp1250 => &CP1250,
            CodePage::Cp1251 => &CP1251,
            CodePage::Cp1252 => &CP1252,
            CodePage::Cp1253 => &CP1253,
            CodePage::Cp1254 => &CP1254,
            CodePage::Cp1257 => &CP1257,
            CodePage::MacRoman => &MAC_ROMAN,
            CodePage::Cp437 => &CP437,
            CodePage::Cp850 => &CP850,
        };
        match table[usize::from(b - 0x80)] {
            0 => char::from(b),
            c => char::from_u32(u32::from(c)).unwrap_or(char::REPLACEMENT_CHARACTER),
        }
    }

    /// The byte that stands for `c`, if the page has one.
    pub fn encode(self, c: char) -> Option<u8> {
        let u = u32::from(c);
        if u < 0x80 {
            return Some(u as u8);
        }
        (0x80..=0xFFu8).find(|&b| u32::from(self.decode(b)) == u && !(0x80..0xA0).contains(&u))
    }
}

